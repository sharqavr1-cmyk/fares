async def spam(target, name, chat):
    count = 0
    while active.get(target):
        insult = generate_insult()
        text = f"{name} {insult}"
        success = await send_with_retry(chat, text)
        if not success:
            break
        count += 1
        await asyncio.sleep(0.7)
    
    if target in active:
        del active[target]
    if target in tasks:
        del tasks[target]

